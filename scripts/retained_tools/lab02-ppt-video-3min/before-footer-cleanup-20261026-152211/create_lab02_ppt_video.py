"""Create a narrated, subtitled recording of a lab02 PPT slideshow.

The original PPTX is opened read-only and never saved. Speech is generated by
edge-tts; only the narration text is sent to the speech service. Intermediates
are cached in --work-dir (legacy default: outputs/qa/lab02-ppt-video).
Use --pptx, --stem and --reference-dir for a separate deck and outputs.
A narration target_duration retimes speech gently to an exact frame budget.
Use --stage prepare/record/render/verify
for recovery, or --stage all for the complete Windows/PowerPoint workflow.
"""
