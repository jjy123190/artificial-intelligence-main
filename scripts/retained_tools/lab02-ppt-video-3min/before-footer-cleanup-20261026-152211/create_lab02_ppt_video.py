ROOT = Path(__file__).resolve().parents[1]
WORK = ROOT / "outputs/qa/lab02-ppt-video"
DELIVERY = ROOT / "deliverables/lab02"
PPTX = DELIVERY / "第31组_推理实验答辩.pptx"
REFERENCES = ROOT / "outputs/qa/lab02-materials/slide-renders"
STEM = "第31组_实验二_PPT讲解录屏"
VIDEO = DELIVERY / (STEM + ".mp4")
SRT = DELIVERY / (STEM + ".srt")
FPS = 30
RATE = 24000


def log(message):
    print(message, flush=True)


def ffmpeg():
    import imageio_ffmpeg
    return imageio_ffmpeg.get_ffmpeg_exe()


def run_ffmpeg(arguments, log_name):
    result = subprocess.run([ffmpeg(), "-hide_banner", "-y", *map(str, arguments)],
                            capture_output=True, encoding="utf-8", errors="replace")
    (WORK / log_name).write_text(result.stderr, encoding="utf-8")
    if result.returncode:
        raise RuntimeError(result.stderr[-5000:])
    return result


def normalized(text):
    return "".join(c for c in unicodedata.normalize("NFKC", text).lower() if c.isalnum())


def load_timeline():
    return json.loads((WORK / "timeline.json").read_text(encoding="utf-8"))


async def synthesize(slide, settings):
    import edge_tts
    text = "".join(c.get("speech", c["text"]) for c in slide["cues"])
    fingerprint = hashlib.sha256(json.dumps(
        [text, settings["voice"], settings["rate"], "WordBoundary"],
        ensure_ascii=False).encode()).hexdigest()
    prefix = WORK / ("voice-%02d" % slide["slide"])
    audio, meta = prefix.with_suffix(".mp3"), prefix.with_suffix(".json")
    if audio.exists() and meta.exists():
        cached = json.loads(meta.read_text(encoding="utf-8"))
        if cached.get("fingerprint") == fingerprint:
            log(f"Reusing slide {slide['slide']} speech")
            return audio, cached["boundaries"]
    for attempt in range(3):
        try:
            boundaries = []
            temp = audio.with_suffix(".partial.mp3")
            communicate = edge_tts.Communicate(
                text, settings["voice"], rate=settings["rate"],
                boundary="WordBoundary", connect_timeout=15, receive_timeout=45)
            with temp.open("wb") as out:
                async for chunk in communicate.stream():
                    if chunk["type"] == "audio":
                        out.write(chunk["data"])
                    elif chunk["type"] == "WordBoundary":
                        boundaries.append({k: chunk[k] for k in ["text", "offset", "duration"]})
            if not boundaries or temp.stat().st_size < 1000:
                raise RuntimeError("Speech service returned incomplete audio or alignment")
            temp.replace(audio)
            meta.write_text(json.dumps({"fingerprint": fingerprint, "speech": text,
                                        "boundaries": boundaries}, ensure_ascii=False, indent=2), encoding="utf-8")
            log(f"Synthesized slide {slide['slide']}: {len(boundaries)} aligned words")
            return audio, boundaries
        except Exception as exc:
            log(f"Speech attempt {attempt + 1} for slide {slide['slide']}: {exc}")
            if attempt == 2:
                raise
            await asyncio.sleep(2 * (attempt + 1))


def timestamp(seconds, ass=False):
    units = 100 if ass else 1000
    ticks = round(seconds * units)
    hours, rest = divmod(ticks, 3600 * units)
    minutes, rest = divmod(rest, 60 * units)
    secs, fraction = divmod(rest, units)
    if ass:
        return f"{hours}:{minutes:02}:{secs:02}.{fraction:02}"
    return f"{hours:02}:{minutes:02}:{secs:02},{fraction:03}"


def write_subtitles(timeline):
    cues = [c for slide in timeline["slides"] for c in slide["cues"]]
    SRT.write_text("\n\n".join(
        f"{i}\n{timestamp(c['start'])} --> {timestamp(c['end'])}\n{c['text']}"
        for i, c in enumerate(cues, 1)) + "\n", encoding="utf-8-sig")
    # Top-center, inside the original 1080p slide. No panel, watermark or group label.
    header = """[Script Info]
ScriptType: v4.00+
PlayResX: 1920
PlayResY: 1080
WrapStyle: 2
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Narration,Microsoft YaHei,42,&H00FFFFFF,&H00FFFFFF,&H002C2825,&H70000000,-1,0,0,0,100,100,0.3,0,1,2,0.5,8,110,110,24,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    events = [f"Dialogue: 0,{timestamp(c['start'], True)},{timestamp(c['end'], True)},Narration,,0,0,0,,{c['text']}" for c in cues]
    (WORK / "subtitles.ass").write_text(header + "\n".join(events) + "\n", encoding="utf-8-sig")


def read_pcm(filename):
    with wave.open(str(filename), "rb") as wav:
        if (wav.getnchannels(), wav.getsampwidth(), wav.getframerate()) != (1, 2, RATE):
            raise ValueError("Expected mono, 16-bit, 24 kHz speech")
        return wav.readframes(wav.getnframes())


def allocate_slide_frames(minimum_frames, target_frames=None):
    if not minimum_frames or any(value <= 0 for value in minimum_frames):
        raise ValueError("Every slide needs a positive frame count")
    if target_frames is None:
        return list(minimum_frames)
    slack = target_frames - sum(minimum_frames)
    if slack < 0:
        raise ValueError("Speech exceeds the target; shorten narration or increase tempo")
    quotient, remainder = divmod(slack, len(minimum_frames))
    return [value + quotient + (index < remainder) for index, value in enumerate(minimum_frames)]


def write_editing_guide(timeline, settings):
    import csv
    guide = DELIVERY / (STEM + "_逐页讲稿.md")
    lines = ["# 实验二三分钟版逐页讲稿", "",
             "成片为180秒、30fps；字幕已烧录，单独SRT用于剪辑，播放时无需再次加载。",
             "原PPT与97秒版保持不变；本版为9页主讲、4页答辩备用。",
             "普通话音轨为合成旁白，不是真人现场发言；不附加底栏、字幕背景面板或水印。", "",
             "## 精确剪辑时间表", "", "| 页 | 入点 | 出点 | 主题 |", "|---|---|---|---|"]
    for slide in timeline["slides"]:
        lines.append(f"| {slide['slide']} | {timestamp(slide['start'])} | {timestamp(slide['end'])} | {slide['title']} |")
    for slide, source in zip(timeline["slides"], settings["slides"]):
        lines.extend(["", f"## 第{slide['slide']}页 · {slide['title']}", "",
                      "".join(cue["text"] for cue in source["cues"])])
    lines.extend(["", "## 阅读边界", "", "三分钟覆盖主要要求与代表性证据，不代替完整报告、全部推导或全部实验表。",
                  "五维比较、敏感性、消融、公式与团队复现入口见PPT备用页；逐项覆盖见同目录《实验二_3分钟版覆盖核查.md》。", ""])
    guide.write_text("\n".join(lines), encoding="utf-8-sig")
    with (DELIVERY / (STEM + "_剪辑时间表.csv")).open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["slide", "start_seconds", "end_seconds", "start_timecode", "end_timecode", "title"])
        for slide in timeline["slides"]:
            writer.writerow([slide["slide"], slide["start"], slide["end"], timestamp(slide["start"]), timestamp(slide["end"]), slide["title"]])


async def prepare():
    settings = json.loads((WORK / "narration.json").read_text(encoding="utf-8"))
    if [slide["slide"] for slide in settings["slides"]] != list(range(1, len(settings["slides"]) + 1)):
        raise ValueError("Narrated slides must be consecutive, starting from 1")
    prepared = []
    for slide in settings["slides"]:
        audio, boundaries = await synthesize(slide, settings)
        raw_wav = audio.with_suffix(".wav")
        run_ffmpeg(["-i", audio, "-ac", 1, "-ar", RATE, "-c:a", "pcm_s16le", raw_wav],
                   f"decode-{slide['slide']:02}.log")
        prepared.append({"source": slide, "audio": audio, "boundaries": boundaries, "pcm": read_pcm(raw_wav),
                         "leading": .75 if slide["slide"] == 1 else .65,
                         "trailing": 1.25 if slide == settings["slides"][-1] else .45})
    target_duration = settings.get("target_duration")
    target_frames = None
    tempo = 1.0
    if target_duration is not None:
        target_frames = round(float(target_duration) * FPS)
        pauses = sum(item["leading"] + item["trailing"] for item in prepared)
        raw_duration = sum(len(item["pcm"]) / (2 * RATE) for item in prepared)
        available = target_frames / FPS - pauses - .5
        if available <= 0:
            raise ValueError("Target is too short for slide pauses")
        tempo = raw_duration / available
        if not .88 <= tempo <= 1.22:
            raise ValueError(f"Required tempo {tempo:.3f} is outside the natural-speech budget; revise narration")
        log(f"Natural speech {raw_duration:.2f}s; tempo {tempo:.4f}; exact target {target_frames / FPS:.2f}s")
        for item in prepared:
            adjusted = WORK / f"voice-{item['source']['slide']:02}-timed.wav"
            run_ffmpeg(["-i", item["audio"], "-af", f"atempo={tempo:.10f}", "-ac", 1,
                        "-ar", RATE, "-c:a", "pcm_s16le", adjusted], f"tempo-{item['source']['slide']:02}.log")
            item["pcm"] = read_pcm(adjusted)
    minimum_frames = [math.ceil((item["leading"] + len(item["pcm"]) / (2 * RATE) + item["trailing"]) * FPS)
                      for item in prepared]
    allocations = allocate_slide_frames(minimum_frames, target_frames)
    slides, pcm_parts, cursor = [], [], 0
    for item, frame_count in zip(prepared, allocations):
        slide, boundaries, pcm = item["source"], item["boundaries"], item["pcm"]
        speech_duration = len(pcm) / (2 * RATE)
        speech = "".join(cue.get("speech", cue["text"]) for cue in slide["cues"])
        aligned = "".join(normalized(boundary["text"]) for boundary in boundaries)
        if aligned != normalized(speech):
            raise RuntimeError(f"Alignment text mismatch on slide {slide['slide']}: {aligned!r} != {normalized(speech)!r}")
        total_samples = frame_count * (RATE // FPS)
        lead_samples = round(item["leading"] * RATE)
        tail_samples = total_samples - lead_samples - len(pcm) // 2
        if tail_samples < 0:
            raise RuntimeError("Narration would be truncated")
        start, speech_start = cursor / RATE, (cursor + lead_samples) / RATE
        entries, position = [], 0
        for boundary in boundaries:
            length = len(normalized(boundary["text"]))
            entries.append({**boundary, "char_start": position, "char_end": position + length})
            position += length
        cues, cue_position = [], 0
        for cue in slide["cues"]:
            length = len(normalized(cue.get("speech", cue["text"])))
            matched = [entry for entry in entries if entry["char_end"] > cue_position and entry["char_start"] < cue_position + length]
            if not matched:
                raise RuntimeError(f"Empty subtitle alignment: {cue}")
            cue_start = speech_start + matched[0]["offset"] / 10_000_000 / tempo
            cue_end = speech_start + (matched[-1]["offset"] + matched[-1]["duration"]) / 10_000_000 / tempo
            cues.append({"text": cue["text"], "start": round(cue_start, 4),
                         "end": round(min(cue_end + .12, start + total_samples / RATE - .10), 4)})
            cue_position += length
        for previous, following in zip(cues, cues[1:]):
            previous["end"] = min(previous["end"], following["start"] - .015)
        if any(cue["end"] <= cue["start"] for cue in cues):
            raise RuntimeError(f"Invalid subtitle interval on slide {slide['slide']}")
        pcm_parts.extend([b"\0\0" * lead_samples, pcm, b"\0\0" * tail_samples])
        cursor += total_samples
        slides.append({"slide": slide["slide"], "title": slide["title"], "start": start, "end": cursor / RATE,
                       "speech_start": speech_start, "speech_duration": speech_duration, "frame_count": frame_count, "cues": cues})
        log(f"Slide {slide['slide']}: {start:.2f}–{cursor / RATE:.2f}s; speech {speech_duration:.2f}s")
    duration = cursor / RATE
    maximum = float(settings.get("max_duration", 120))
    if duration > maximum + .001 or (target_duration is None and duration >= maximum):
        raise RuntimeError(f"Narration lasts {duration:.2f}s, exceeding maximum {maximum}s")
    with wave.open(str(WORK / "narration.wav"), "wb") as wav:
        wav.setnchannels(1)
        wav.setsampwidth(2)
        wav.setframerate(RATE)
        wav.writeframes(b"".join(pcm_parts))
    timeline = {"duration": duration, "target_duration": target_duration, "maximum_duration": maximum,
                "fps": FPS, "voice": settings["voice"], "rate": settings["rate"], "tempo_factor": tempo,
                "source_pptx": str(PPTX.relative_to(ROOT)), "source_sha256": hashlib.sha256(PPTX.read_bytes()).hexdigest(),
                "reference_dir": str(REFERENCES.relative_to(ROOT)), "slides": slides}
    (WORK / "timeline.json").write_text(json.dumps(timeline, ensure_ascii=False, indent=2), encoding="utf-8")
    write_subtitles(timeline)
    if target_duration is not None:
        write_editing_guide(timeline, settings)
    log(f"Prepared {len(slides)} slides, duration {duration:.3f}s, {sum(len(slide['cues']) for slide in slides)} subtitles")


def record(probe=False):
    import pythoncom
    import win32com.client
    import win32gui
    pythoncom.CoInitialize()
    ctypes.windll.user32.SetProcessDPIAware()
    timeline = load_timeline()
    app, deck, show, process = None, None, None, None
    old_window = win32gui.GetForegroundWindow()
    log_file = None
    try:
        app = win32com.client.DispatchEx("PowerPoint.Application")
        deck = app.Presentations.Open(str(PPTX), True, False, False)
        settings = deck.SlideShowSettings
        settings.ShowType = 3  # ppShowTypeKiosk; no editor, taskbar or playback controls.
        settings.RangeType = 2  # ppShowSlideRange
        settings.StartingSlide = 1
        settings.EndingSlide = timeline["slides"][-1]["slide"]
        settings.AdvanceMode = 1  # ppSlideShowManualAdvance
        settings.LoopUntilStopped = False
        existing_windows = set()
        win32gui.EnumWindows(lambda hwnd, _: existing_windows.add(hwnd), None)
        show = settings.Run()
        time.sleep(1.5)
        candidates = []

        def find_window(hwnd, _):
            if hwnd in existing_windows or not win32gui.IsWindowVisible(hwnd):
                return
            client_rect = win32gui.GetClientRect(hwnd)
            if client_rect[2:] != (1920, 1080):
                return
            class_name = win32gui.GetClassName(hwnd)
            title = win32gui.GetWindowText(hwnd)
            score = 4 if class_name.lower() == "screenclass" else 0
            if "slide" in title.lower() or "幻灯片" in title or "放映" in title:
                score += 2
            candidates.append((score, hwnd, class_name, title))

        win32gui.EnumWindows(find_window, None)
        if not candidates:
            raise RuntimeError("Cannot find the new 1920x1080 slideshow window")
        candidates.sort(reverse=True)
        _, hwnd, window_class, window_title = candidates[0]
        log(f"Using slideshow window {hwnd}: {window_class} {window_title!r}")
        show.View.GotoSlide(1)
        show.View.State = 2
        if int(show.View.CurrentShowPosition) != 1:
            raise RuntimeError("Slideshow did not settle on slide 1")
        client = win32gui.GetClientRect(hwnd)
        window_rect = win32gui.GetWindowRect(hwnd)
        if client[2:] != (1920, 1080):
            raise RuntimeError(f"Expected 1920x1080 slideshow, got {client}; refusing desktop crop")
        if (window_rect[2] - window_rect[0], window_rect[3] - window_rect[1]) != (1920, 1080):
            raise RuntimeError(f"Expected borderless 1920x1080 slideshow, got {window_rect}")
        win32gui.SetWindowPos(hwnd, -1, 0, 0, 0, 0, 0x0001 | 0x0002 | 0x0010)
        win32gui.BringWindowToTop(hwnd)
        try:
            win32gui.SetForegroundWindow(hwnd)
        except Exception:
            pass
        time.sleep(0.5)
        source_before = hashlib.sha256(PPTX.read_bytes()).hexdigest()
        if probe:
            raw = WORK / "probe.mkv"
            duration = 3
        else:
            raw = WORK / "slideshow-raw.mkv"
            duration = timeline["duration"] + 2.0
        log_file = (WORK / ("capture-probe.log" if probe else "capture.log")).open("w", encoding="utf-8")
        command = [ffmpeg(), "-hide_banner", "-y", "-f", "gdigrab", "-framerate", str(FPS),
                   "-offset_x", str(window_rect[0]), "-offset_y", str(window_rect[1]),
                   "-video_size", "1920x1080", "-draw_mouse", "0", "-i", "desktop",
                   "-t", str(duration),
                   "-an", "-c:v", "libx264", "-preset", "ultrafast", "-crf", "16",
                   "-pix_fmt", "yuv420p", "-fps_mode", "cfr", "-r", str(FPS), str(raw)]
        started = time.perf_counter()
        process = subprocess.Popen(command, stdout=subprocess.DEVNULL, stderr=log_file,
                                   stdin=subprocess.PIPE, creationflags=subprocess.CREATE_NO_WINDOW)
        changes = [{"slide": 1, "scheduled": 0, "actual": 0}]
        if not probe:
            # Capture gets a short warm-up, which is removed in the rendering stage.
            warmup = 0.8
            for slide in timeline["slides"][1:]:
                target = started + warmup + slide["start"]
                while time.perf_counter() < target:
                    if process.poll() is not None:
                        raise RuntimeError("Capture stopped unexpectedly; see capture.log")
                    pythoncom.PumpWaitingMessages()
                    time.sleep(min(0.01, max(0, target - time.perf_counter())))
                show.View.GotoSlide(slide["slide"])
                show.View.State = 2
                if int(show.View.CurrentShowPosition) != slide["slide"]:
                    raise RuntimeError(f"Slideshow did not settle on slide {slide['slide']}")
                actual = time.perf_counter() - started
                changes.append({"slide": slide["slide"], "scheduled": warmup + slide["start"], "actual": actual})
                log(f"Recorded slide {slide['slide']} at {actual:.3f}s")
        while process.poll() is None:
            pythoncom.PumpWaitingMessages()
            time.sleep(0.05)
        if process.returncode:
            raise RuntimeError(f"Recording failed, exit {process.returncode}; see capture log")
        if not probe:
            (WORK / "capture-events.json").write_text(json.dumps(
                {"window_handle": hwnd, "window_client_size": list(client[2:]),
                 "source": "PowerPoint slideshow desktop region via gdigrab", "warmup": warmup,
                 "changes": changes}, ensure_ascii=False, indent=2), encoding="utf-8")
        if hashlib.sha256(PPTX.read_bytes()).hexdigest() != source_before:
            raise RuntimeError("Original PPTX unexpectedly changed")
        log(f"Saved real PowerPoint recording: {raw}")
    finally:
        if process and process.poll() is None:
            try:
                process.communicate(b"q", timeout=10)
            except Exception:
                process.terminate()
                process.wait(timeout=10)
        if log_file:
            log_file.close()
        if show:
            try:
                show.View.Exit()
            except Exception:
                pass
        if deck:
            try:
                deck.Close()
            except Exception:
                pass
        if app:
            try:
                if app.Presentations.Count == 0:
                    app.Quit()
            except Exception:
                pass
        try:
            if old_window:
                win32gui.SetForegroundWindow(old_window)
        except Exception:
            pass
        pythoncom.CoUninitialize()


def render():
    timeline = load_timeline()
    capture = json.loads((WORK / "capture-events.json").read_text(encoding="utf-8"))
    # The recording is indexed during QA; prefer measured rather than assumed offset.
    offset = capture.get("measured_trim", capture["warmup"])
    relative_ass = (WORK / "subtitles.ass").relative_to(ROOT).as_posix()
    temp_output = WORK / "final-pending.mp4"
    run_ffmpeg(["-ss", offset, "-i", WORK / "slideshow-raw.mkv", "-i", WORK / "narration.wav",
                "-t", timeline["duration"], "-map", "0:v:0", "-map", "1:a:0",
                "-vf", f"ass=filename='{relative_ass}'", "-c:v", "libx264", "-preset", "medium",
                "-crf", "18", "-pix_fmt", "yuv420p", "-r", FPS,
                "-af", "loudnorm=I=-16:TP=-1.5:LRA=7", "-ar", "48000", "-ac", "2",
                "-c:a", "aac", "-b:a", "192k", "-movflags", "+faststart",
                "-metadata", f"title={STEM}", "-metadata", "comment=普通话合成旁白；字幕内嵌；原PPT放映窗口录制",
                temp_output], "render.log")
    if VIDEO.exists():
        backup = WORK / ("previous-" + time.strftime("%Y%m%d-%H%M%S") + ".mp4")
        VIDEO.replace(backup)
    temp_output.replace(VIDEO)
    log(f"Rendered {VIDEO}")


def verify():
    import cv2
    import numpy as np
    from PIL import Image, ImageDraw, ImageFont
    timeline = load_timeline()
    result = run_ffmpeg(["-v", "error", "-i", VIDEO, "-map", "0:v:0", "-map", "0:a:0", "-f", "null", "-"], "full-decode.log")
    if result.stderr.strip():
        raise RuntimeError("Decode warnings/errors: " + result.stderr)
    cap = cv2.VideoCapture(str(VIDEO))
    fps = cap.get(cv2.CAP_PROP_FPS)
    frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    width, height = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH)), int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    duration = frames / fps
    assert (width, height) == (1920, 1080), (width, height)
    assert abs(fps - FPS) < .01
    assert duration <= timeline.get("maximum_duration", 120) + .001
    assert abs(duration - timeline["duration"]) < .05
    if timeline.get("target_duration") is not None:
        assert frames == round(timeline["target_duration"] * FPS)
    numbers = [slide["slide"] for slide in timeline["slides"]]
    references, full_references = [], []
    for number in numbers:
        reference = cv2.imread(str(REFERENCES / f"slide-{number:02}.png"))
        if reference is None:
            raise RuntimeError(f"Missing slide reference {number}")
        references.append(cv2.resize(reference, (320, 180)).astype(np.float32))
        full_references.append(cv2.resize(reference, (1920, 1080)))

    def frame_at(second):
        cap.set(cv2.CAP_PROP_POS_MSEC, second * 1000)
        ok, frame = cap.read()
        if not ok:
            raise RuntimeError(f"Cannot read frame at {second:.3f}s")
        return frame

    def match(frame, slide_number, second):
        sample = cv2.resize(frame, (320, 180)).astype(np.float32)
        errors = [float(np.mean((sample[16:] - reference[16:]) ** 2)) for reference in references]
        best = int(np.argmin(errors))
        if numbers[best] != slide_number or errors[best] > 1200:
            raise RuntimeError(f"At {second:.3f}s expected slide {slide_number}, detected {numbers[best]}, MSE {errors[best]:.1f}")
        bottom_error = float(np.mean(np.abs(frame[-12:].astype(np.float32) - full_references[best][-12:].astype(np.float32))))
        if bottom_error > 18:
            raise RuntimeError(f"Unexpected bottom overlay/taskbar at {second:.3f}s: {bottom_error:.2f}")
        return {"slide": slide_number, "timestamp": round(second, 4), "detected_slide": numbers[best],
                "match_mse": errors[best], "bottom_strip_error": bottom_error}

    samples, subtitle_checks, continuous = [], [], []
    columns = 3 if len(numbers) > 6 else 2
    cell_width = 1920 // columns
    cell_height = round(cell_width * 9 / 16) + 34
    sheet = Image.new("RGB", (1920, math.ceil(len(numbers) / columns) * cell_height), "#dedbd6")
    draw = ImageDraw.Draw(sheet)
    font = ImageFont.truetype("C:/Windows/Fonts/msyh.ttc", 21)
    for index, slide in enumerate(timeline["slides"]):
        cue = max(slide["cues"], key=lambda entry: len(entry["text"]))
        second = (cue["start"] + cue["end"]) / 2
        frame = frame_at(second)
        samples.append(match(frame, slide["slide"], second))
        image = Image.fromarray(cv2.cvtColor(frame, cv2.COLOR_BGR2RGB))
        image.save(WORK / f"final-slide-{slide['slide']:02}.png")
        xpos, ypos = (index % columns) * cell_width, (index // columns) * cell_height
        draw.text((xpos + 12, ypos + 4), f"{slide['slide']:02}  {second:.2f}s", font=font, fill="#333333")
        sheet.paste(image.resize((cell_width, cell_height - 34)), (xpos, ypos + 34))
        for cue in slide["cues"]:
            cue_second = (cue["start"] + cue["end"]) / 2
            cue_frame = frame_at(cue_second)
            match(cue_frame, slide["slide"], cue_second)
            difference = np.max(np.abs(cue_frame[:88].astype(np.int16) - full_references[index][:88].astype(np.int16)), axis=2)
            changed_pixels = int(np.count_nonzero(difference > 24))
            if changed_pixels < 120:
                raise RuntimeError(f"Subtitle not visible at {cue_second:.3f}s: {cue['text']}")
            subtitle_checks.append({"slide": slide["slide"], "timestamp": cue_second, "changed_pixels": changed_pixels})
        for second in np.arange(slide["start"] + .55, slide["end"] - .40, 1.0):
            continuous.append(match(frame_at(float(second)), slide["slide"], float(second)))
    cap.release()
    sheet.save(WORK / "final-contact.png")
    volume = run_ffmpeg(["-i", VIDEO, "-af", "volumedetect", "-vn", "-f", "null", "-"], "volume.log")
    volume_lines = [line.strip() for line in volume.stderr.splitlines() if "mean_volume" in line or "max_volume" in line]
    probe = subprocess.run([ffmpeg(), "-hide_banner", "-i", str(VIDEO)], capture_output=True, encoding="utf-8", errors="replace")
    streams = [line.strip() for line in probe.stderr.splitlines() if "Stream #" in line or "Duration:" in line]
    assert any("Audio: aac" in line for line in streams), streams
    assert hashlib.sha256(PPTX.read_bytes()).hexdigest() == timeline["source_sha256"]
    report = {"video": str(VIDEO.relative_to(ROOT)), "duration_seconds": duration, "resolution": [width, height],
              "fps": fps, "frame_count": frames, "bytes": VIDEO.stat().st_size,
              "subtitle_cues": sum(len(slide["cues"]) for slide in timeline["slides"]),
              "slide_count": len(timeline["slides"]), "full_decode": "passed", "original_pptx_unchanged": True,
              "streams": streams, "volume": volume_lines, "voice": timeline["voice"], "tempo_factor": timeline.get("tempo_factor", 1),
              "samples": samples, "subtitle_render_checks": subtitle_checks, "continuous_slide_checks": continuous}
    (WORK / "verification.json").write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    log(json.dumps({key: value for key, value in report.items() if key not in ["samples", "subtitle_render_checks", "continuous_slide_checks"]}, ensure_ascii=False, indent=2))
    log(f"Verified {len(continuous)} continuous slide samples and {len(subtitle_checks)} rendered subtitle cues")


def main():
    global WORK, PPTX, REFERENCES, STEM, VIDEO, SRT
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stage", choices=["all", "prepare", "probe", "record", "render", "verify"], default="all")
    parser.add_argument("--work-dir", type=Path, default=WORK)
    parser.add_argument("--pptx", type=Path, default=PPTX)
    parser.add_argument("--reference-dir", type=Path, default=REFERENCES)
    parser.add_argument("--stem", default=STEM)
    args = parser.parse_args()
    def in_workspace(value):
        result = (ROOT / value).resolve() if not value.is_absolute() else value.resolve()
        result.relative_to(ROOT.resolve())
        return result
    WORK, PPTX, REFERENCES = map(in_workspace, [args.work_dir, args.pptx, args.reference_dir])
    if Path(args.stem).name != args.stem or any(character in args.stem for character in '/\\:'):
        raise ValueError("Output stem must be a filename, not a path")
    STEM = args.stem
    VIDEO, SRT = DELIVERY / (STEM + ".mp4"), DELIVERY / (STEM + ".srt")
    WORK.mkdir(parents=True, exist_ok=True)
    import os
    os.chdir(ROOT)
    if args.stage in ["all", "prepare"]:
        asyncio.run(prepare())
    if args.stage == "probe":
        record(probe=True)
    if args.stage in ["all", "record"]:
        record()
    if args.stage in ["all", "render"]:
        render()
    if args.stage in ["all", "verify"]:
        verify()


if __name__ == "__main__":
    main()
